"""Builds the wall box's own web page (aankhen/firmware/web_page.h) from the phone app.

One phone app, one relays view: phone_page/relays.js and relays.css are the tiles the
JARVIS phone app shows, and the board's page at http://<board>/ inlines the same two files
into phone_page/board.html. The board serves one self-contained page (no second request,
no CDN), so the build step pastes them in instead of linking them.

    python -m jarvis_app.board_page          # rewrite web_page.h, then compile the firmware

test_board_page.py fails when web_page.h differs from what this would write, so the board
page cannot drift from the app by a hand edit.
"""
from __future__ import annotations

import sys
from pathlib import Path

PAGE_DIR = Path(__file__).resolve().parent / "phone_page"
OUT = Path(__file__).resolve().parents[2] / "aankhen" / "firmware" / "web_page.h"
DELIM = "HTML"                                 # the C++ raw string: R"HTML( ... )HTML"
# ESP32 HTTP send_P streams from flash; the beacon page is 8 KB. Past this the page is
# probably carrying something it should not.
MAX_BYTES = 24_000


def render() -> str:
    page = (PAGE_DIR / "board.html").read_text(encoding="utf-8")
    css = (PAGE_DIR / "relays.css").read_text(encoding="utf-8")
    js = (PAGE_DIR / "relays.js").read_text(encoding="utf-8")
    for marker in ("/*RELAYS_CSS*/", "/*RELAYS_JS*/"):
        if page.count(marker) != 1:
            raise ValueError(f"board.html must hold {marker} exactly once")
    page = page.replace("/*RELAYS_CSS*/", css.strip()).replace("/*RELAYS_JS*/", js.strip())
    page = page.replace("\r\n", "\n")
    if f'){DELIM}"' in page:
        raise ValueError(f'the page contains ){DELIM}" and would end the C++ raw string early')
    if len(page.encode("utf-8")) > MAX_BYTES:
        raise ValueError(f"the board page is {len(page.encode('utf-8'))} B, over {MAX_BYTES} B")
    return (
        "#pragma once\n"
        "#include <Arduino.h>\n\n"
        "// GENERATED by app/jarvis_app/board_page.py from app/jarvis_app/phone_page/\n"
        "// board.html + relays.js + relays.css. Do not edit here: edit those, then run\n"
        "//   python -m jarvis_app.board_page\n"
        "// Served at GET / : opens the JARVIS phone app when JARVIS answers, otherwise the\n"
        "// relays-only view, which talks to POST /relay and GET /status with the board token.\n"
        f'static const char WEB_PAGE_HTML[] PROGMEM = R"{DELIM}(' + page + f'){DELIM}";\n'
    )


def main() -> int:
    text = render()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT}: {len(text.encode('utf-8'))} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
