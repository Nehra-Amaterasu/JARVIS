// Golden vectors (spec 9.13 P-6, V-01, V-10): a small JSON file of input rows and the geometry the pure functions give.
// `voice-golden.json` is committed. UPDATE_GOLDEN=1 rewrites it from the functions, so a deliberate change to the map is
// one command and one reviewed diff; without the flag the test fails on any drift.
//
// The Python side can check the same file (docs/research/voice.md): `bandMap.edges` against core.playback.band_edges(),
// `bandMap.freqToBand` by running playback.analyse() on a sine at each frequency (the loudest band must be the listed one),
// `bandMap.dbToByte` against np.rint(255 * np.clip((db - lo) / 60, 0, 1)), and `hill.high.layer0Heights` from `rows[0]` by
// the 12-line numpy recipe in the research file. The geometry hashes are TypeScript-only: they pin how the picture is drawn.
import { describe, expect, it } from 'vitest'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { bandEdges, bandOfFrequency, dbToByte, lerpBand } from '../../jarvis/voice/bands'
import { ATTACK_MS, HILL_MAX_H, N_BANDS, RELEASE_MS, smoothCoef } from '../../jarvis/voice/constants'
import { colBand, colX, envelopeGeometry, hillGeometry, placeholderHill, ringBars, ringLengthsBands, ringLengthsPlaceholder, type Points } from '../../jarvis/voice/geometry'
import { bandsOf, speechRow } from './voice-helpers'

const FILE = join(__dirname, 'voice-golden.json')

const r1 = (n: number) => Math.round(n * 10) / 10
const r3 = (n: number) => Math.round(n * 1000) / 1000
/** FNV-1a over the coordinates rounded to 0.01: a compact fingerprint of a point set. */
function hashPoints(p: { count: number; x: ArrayLike<number>; y: ArrayLike<number> }): string {
  let h = 0x811c9dc5
  const mix = (v: number) => {
    h ^= v & 0xffffffff
    h = Math.imul(h, 0x01000193) >>> 0
  }
  for (let i = 0; i < p.count; i++) {
    mix(Math.round(p.x[i] * 100))
    mix(Math.round(p.y[i] * 100))
  }
  return h.toString(16).padStart(8, '0')
}
const sample = (p: Points, n = 8) => Array.from({ length: n }, (_, i) => {
  const k = Math.floor((i * (p.count - 1)) / (n - 1))
  return [r3(p.x[k]), r3(p.y[k])]
})

const ROW0 = speechRow(1)
const ROW1 = speechRow(0.7)
const ROW2 = bandsOf((i) => 20 + 6 * i)
const ROWS = [ROW0, ROW1, ROW2, null, ROW2, ROW1, ROW0, null]
const SCALAR: [number, number][] = [[0, 0], [400, 2], [800, 6], [1200, 9], [1600, 3], [2000, 1], [2400, 4]]

function build() {
  const centres = [0, 4, 8, 12, 16, 20, 23].map((i) => r3(100 * Math.pow(80, (i + 0.5) / N_BANDS)))
  const freqs = [99, 100, 431, 894, 1000, 1700, 3854, 6665, 7999, 8000, ...centres]
  const high = hillGeometry(ROWS, 'high')
  const low = hillGeometry(ROWS, 'low')
  const rb = ringBars(ringLengthsBands(ROW0))
  const ph = placeholderHill('high', 1)
  const phr = ringBars(ringLengthsPlaceholder(0))
  const env = envelopeGeometry(SCALAR, 2400)
  return {
    version: 1,
    note: 'Generated by src/__tests__/jarvis/voice-golden.test.ts (UPDATE_GOLDEN=1). Rows are smoothed 24-band rows, 0..255. Spec 9.13 P-6.',
    bandMap: {
      edges: bandEdges().map(r3),
      freqToBand: freqs.map((f) => [f, bandOfFrequency(f)]),
      dbToByte: {
        out: [-90, -60, -45, -30, -20, -10, 0, 6].map((db) => [db, dbToByte(db, 'out')]),
        in: [-90, -70, -55, -40, -23, -10, 0, 6].map((db) => [db, dbToByte(db, 'in')]),
      },
      smoothing: { attack50: r3(smoothCoef(50, ATTACK_MS)), release50: r3(smoothCoef(50, RELEASE_MS)) },
    },
    rows: { row0: ROW0, row1: ROW1, row2: ROW2, historyOrder: [0, 1, 2, null, 2, 1, 0, null] },
    hill: {
      high: { count: high.count, hash: hashPoints(high), layer0Heights: Array.from({ length: 96 }, (_, c) => r1((HILL_MAX_H * lerpBand(ROW0, colBand(colX(c, 96)))) / 255)), sample: sample(high) },
      low: { count: low.count, hash: hashPoints(low), sample: sample(low) },
    },
    ring: { lengths: Array.from(ringLengthsBands(ROW0)).map(r3), hash: hashPoints({ count: 96, x: rb.x1, y: rb.y1 }), belowCount: rb.below.reduce((a, b) => a + b, 0) },
    placeholder: { hillCount: ph.count, hillHash: hashPoints(ph), ringHash: hashPoints({ count: 96, x: phr.x1, y: phr.y1 }) },
    envelope: { scalar: SCALAR, now: 2400, count: env.count, hash: hashPoints(env) },
  }
}

describe('golden vectors (P-6, V-01, V-10)', () => {
  const got = build()
  if (process.env.UPDATE_GOLDEN === '1') writeFileSync(FILE, JSON.stringify(got, null, 1) + '\n', 'utf8')
  const want = JSON.parse(readFileSync(FILE, 'utf8'))

  it('V-01: the band map and the dB window equal the committed vectors', () => {
    expect(got.bandMap).toEqual(want.bandMap)
    // the named facts of spec 9.2 and P-1/P-7, independent of the file: a 1 kHz sine is band 12, 1.7 kHz is band 15
    expect(bandOfFrequency(1000)).toBe(12)
    expect(bandOfFrequency(1700)).toBe(15)
    expect(want.bandMap.edges).toHaveLength(25)
    expect(want.bandMap.smoothing).toEqual({ attack50: 0.713, release50: 0.268 })
  })

  it('V-10: the hill geometry equals the committed array (3,072 points high, 1,280 low), inside 720 x 360, no NaN', () => {
    expect(got.hill).toEqual(want.hill)
    expect(want.hill.high.count).toBeLessThan(3072) // two of the eight layers have no real frame, so they are absent, not invented
    const all = hillGeometry([ROW0, ROW1, ROW0, ROW1, ROW0, ROW1, ROW0, ROW1], 'high')
    expect(all.count).toBe(3072)
    for (let i = 0; i < all.count; i++) {
      expect(Number.isFinite(all.x[i]) && Number.isFinite(all.y[i])).toBe(true)
      expect(all.x[i]).toBeGreaterThanOrEqual(0)
      expect(all.x[i]).toBeLessThanOrEqual(720)
      expect(all.y[i]).toBeGreaterThanOrEqual(0)
      expect(all.y[i]).toBeLessThanOrEqual(360)
    }
    expect(hillGeometry([ROW0, ROW1, ROW0, ROW1, ROW0], 'low').count).toBe(1280)
  })

  it('the ring, the placeholder and the tier-0 envelope equal the committed vectors', () => {
    expect(got.ring).toEqual(want.ring)
    expect(got.placeholder).toEqual(want.placeholder)
    expect(got.envelope).toEqual(want.envelope)
  })

  it('the file is small (under 12 KB)', () => {
    expect(readFileSync(FILE).length).toBeLessThan(12 * 1024)
  })
})
