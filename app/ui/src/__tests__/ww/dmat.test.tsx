// Chunk 7: Study > dMAT (plan 4.15, 8.1 "dMAT"). The generators are the server's; here the route is a stub that is
// deterministic in the seed, which is the property the page relies on.
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act } from 'react'
import { mount, resetHtml } from './_stubs'
import { $, $$, byText, click, settle, stubApi, type } from './_study'
import { PrimaryOwner } from '../../ww/kit'
import { resetFrameStore, useFrame } from '../../ww/frame/frameStore'
import { Dmat } from '../../ww/study/Dmat'
import { StudyPage } from '../../ww/study/StudyPage'
import { resetStudyStore } from '../../ww/study/studyStore'

let m: ReturnType<typeof mount> | null = null
beforeEach(() => {
  vi.stubGlobal('IntersectionObserver', class { observe() {} unobserve() {} disconnect() {} })
})
afterEach(() => {
  m?.unmount()
  m = null
  resetStudyStore()
  resetFrameStore()
  vi.unstubAllGlobals()
  vi.useRealTimers()
  resetHtml()
  document.body.innerHTML = ''
})

const equation = (seed: number, i: number) => ({
  i, kind: 'equation', prompt: `Find A + ${seed % 7 + i}*B`, unknowns: ['A', 'B'], range: [1, 12], rule: 'whole numbers', equations: [`B - ${seed % 5} = ${i + 2}`, '2*A = 6'], ask: 'A', options: [{ text: '3' }, { text: '5' }, { text: '8' }],
})
const setFor = (kind: string, seed: number, level: number, n: number) => ({
  set_id: `${kind}-${seed}-L${level}-n${n}`, kind, label: kind === 'equation' ? 'Equations' : kind === 'latin' ? 'Latin squares' : 'Figure sequences', seed, level, n,
  seconds_per_item: 60, time_limit_s: 60 * n, rules: 'Rules are public.', items: Array.from({ length: n }, (_, i) => equation(seed, i)),
})

function routes(history: object[] = []) {
  const r = stubApi([
    ['GET', /\/dmat\/set\?/, (url) => {
      const q = new URL(url, 'http://x').searchParams
      return setFor(q.get('kind')!, Number(q.get('seed')), Number(q.get('level')), Number(q.get('n')))
    }],
    ['GET', /\/dmat\/history/, () => ({ results: history, empty: history.length === 0 })],
    ['POST', /\/dmat\/score$/, (_u, body) => {
      const b = body as { set_id: string; answers: (number | null)[]; seconds: number }
      const correct = b.answers.filter((a) => a === 0).length
      return { set_id: b.set_id, kind: 'equation', correct, of: b.answers.length, unanswered: b.answers.filter((a) => a === null).length, pct: 0, seconds: b.seconds, time_limit_s: 600, in_time: true, items: [] }
    }],
  ])
  return r
}

async function open(el = <Dmat />) {
  m = mount(<PrimaryOwner>{el}</PrimaryOwner>)
  await settle()
}

describe('dMAT', () => {
  it('is the fourth Study view', async () => {
    routes()
    useFrame.setState({ view: 'dmat' })
    await open(<StudyPage />)
    expect($('[data-view=dmat]')).not.toBeNull()
    expect($$('[aria-label="Study views"] [role=radio]').find((r) => r.getAttribute('aria-checked') === 'true')!.textContent).toBe('dMAT')
  })
  it('offers three task kinds, a length, a level and a timer, and Start set is the view\'s primary', async () => {
    routes()
    await open()
    const labels = (name: string) => $$(`[role=radiogroup][aria-label="${name}"] [role=radio]`).map((r) => r.textContent)
    expect(labels('Task kind')).toEqual(['Figure sequences', 'Equations', 'Latin squares'])
    expect(labels('Length')).toEqual(['10 tasks', '20 tasks', '30 tasks'])
    expect(labels('Level')).toEqual(['Level 1', 'Level 2', 'Level 3'])
    expect(labels('Timer')).toEqual(['Timer on', 'Timer off'])
    const start = byText('Start set')!
    expect(start.getAttribute('data-primary')).toBe('true')
    expect($$('[data-primary]')).toHaveLength(1)
  })
  it('says the items are generated here, none copied from the test, and that the levels are uncalibrated practice', async () => {
    routes()
    await open()
    const t = $('[data-dmat-rules]')!.textContent!
    expect(t).toContain('every item is generated by this app')
    expect(t).toContain('None is copied from the test')
    expect(t).toContain('uncalibrated')
  })
  it('with no set taken it says "No set taken yet."; with a history it prints the last set', async () => {
    routes()
    await open()
    expect($('[data-dmat-last]')!.textContent).toBe('No set taken yet.')
    m!.unmount()
    m = null
    routes([{ set_id: 'equation-1-L2-n10', kind: 'equation', level: 2, n: 10, correct: 7, of: 10, seconds: 180, time_limit_s: 600, in_time: true, date: '2026-11-09' }])
    await open()
    expect($('[data-dmat-last]')!.textContent).toBe('Last set: 7 of 10 correct in 3 min (Equations, level 2).')
  })
  it('a set with the same seed shows the same tasks', async () => {
    const r = routes()
    const run = async () => {
      await click(byText('Equations', '[role=radio]'))
      type($('input[type=number]') as HTMLInputElement, '4242')
      await click(byText('Start set'))
      await settle()
      const text = $('[data-dmat-run]')!.textContent
      expect(r.calls.at(-1)!.url).toMatch(/kind=equation&seed=4242&n=10&level=1/)
      return text
    }
    await open()
    const a = await run()
    m!.unmount()
    m = null
    await open()
    const b = await run()
    expect(a).toBe(b)
    expect(a).toContain('Equations · level 1 · seed 4242 · task 1 of 10')
  })
  it('runs a set, scores it on the server, and the score line counts correct answers only', async () => {
    const r = routes()
    await open()
    await click(byText('Equations', '[role=radio]'))
    await click(byText('Timer off', '[role=radio]'))
    await click(byText('Start set'))
    await settle()
    expect($('[data-dmat-run]')!.textContent).not.toContain('left')
    // answer 3 tasks with option A (the stub's right answer), skip the rest
    for (let i = 0; i < 3; i++) {
      await click($$('[role=radio][aria-label="Answer"], [role=radiogroup][aria-label=Answer] [role=radio]')[0])
      await click(byText('Next'))
    }
    await click(byText('Finish and score'))
    await settle()
    const post = r.calls.find((c) => c.method === 'POST')!
    expect((post.body as { answers: unknown[] }).answers.slice(0, 4)).toEqual([0, 0, 0, null])
    expect((post.body as { set_id: string }).set_id).toMatch(/^equation-\d+-L1-n10$/)
    const out = $('[data-dmat-result]')!.textContent!
    expect(out).toContain('3 of 10 correct, 7 not answered')
    expect(out).toContain('Saved to your history')
  })
  it('a timed set shows the clock and marks itself when it reaches zero', async () => {
    vi.useFakeTimers({ toFake: ['setTimeout', 'clearTimeout', 'Date'] })
    const r = routes()
    r.on('GET', /\/dmat\/set\?/, () => ({ ...setFor('equation', 5, 1, 10), time_limit_s: 3 }))
    m = mount(<PrimaryOwner><Dmat /></PrimaryOwner>)
    await act(async () => { await vi.advanceTimersByTimeAsync(10) })
    await click(byText('Start set'))
    await act(async () => { await vi.advanceTimersByTimeAsync(10) })
    expect($('[data-dmat-run]')!.textContent).toContain('0:03 left')
    // one tick per act: each second is a state change the next timer waits for
    for (let i = 0; i < 4; i++) await act(async () => { await vi.advanceTimersByTimeAsync(1000) })
    await act(async () => { await vi.advanceTimersByTimeAsync(10) })
    expect(r.calls.some((c) => c.method === 'POST' && /dmat\/score/.test(c.url))).toBe(true)
    expect($('[data-dmat-result]')).not.toBeNull()
  })
  it('a refused set shows the server\'s words', async () => {
    const r = routes()
    r.on('GET', /\/dmat\/set\?/, () => ({ __status: 400, body: { detail: 'n is 1 to 60' } }))
    await open()
    await click(byText('Start set'))
    await settle()
    expect($('[role=alert]')!.textContent).toBe('n is 1 to 60')
  })
  it('with the dMAT routes absent the view falls back to the registry line', async () => {
    stubApi([])
    await open()
    expect($('[data-planned="dmat-practice"], [data-view=dmat]')!.textContent).toContain('dMAT practice is not built.')
    expect(byText('Start set')).toBeNull()
  })
})
