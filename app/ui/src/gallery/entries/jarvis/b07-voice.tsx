// The voice picture (B07 UI half). The gallery has no microphone, so it feeds the real component one FIXTURE frame, stamped
// SIMULATED, and shows the states that need no frame at all. The picture itself draws points only while a frame younger than
// 400 ms exists, so the fixture reads as live for 0.4 s and then falls to NO SIGNAL: the transition is the honest part.
// Motion is forced off here (the static form), so the gallery adds no animation loop.
import { useEffect, useMemo } from 'react'
import { Frame } from '../../../shared/kit'
import { VoiceHill, VoiceSignal, N_BANDS, type CoreView, type VoiceFrame } from '../../../jarvis/voice'
import type { GalleryEntryX } from '../../types'

const core = (o: Partial<CoreView> = {}): CoreView => ({ running: true, state: 'idle', stateSince: null, lastError: null, muted: false, ...o })

/** A speech-shaped spectrum, computed from a formula: a fixture, not a recording. */
const FIXTURE_BANDS = Array.from({ length: N_BANDS }, (_, i) => Math.round(40 + 170 * Math.exp(-((i - 7) ** 2) / 30)))

function Fixture() {
  const signal = useMemo(() => new VoiceSignal(), [])
  useEffect(() => {
    const at = Date.now()
    const f: VoiceFrame = {
      channel: 'in', t: at / 1000, seq: 0, sr: 24000, rmsDb: -23, peakDb: null, bands: FIXTURE_BANDS, level: null, latMs: null, final: false,
      thrDb: null, speechProb: null, vadThreshold: null, speaking: null, arrival: at,
    }
    signal.ingest(f)
  }, [signal])
  return (
    <Frame state="simulated" reason="fixture frame generated by the gallery, not a microphone" stamp="SIMULATED">
      <VoiceHill signal={signal} core={core({ state: 'listening', stateSince: Date.now() })} motion="none" />
    </Frame>
  )
}
function Idle() {
  const signal = useMemo(() => new VoiceSignal(), [])
  return <VoiceHill signal={signal} core={core()} motion="none" />
}
function Off() {
  const signal = useMemo(() => new VoiceSignal(), [])
  return <VoiceHill signal={signal} core={core({ running: false })} motion="none" />
}

const entries: GalleryEntryX[] = [
  {
    id: 'voice/VoiceHill',
    title: 'VoiceHill',
    group: 'voice',
    merged: 'voice picture, 13 Nov',
    note: 'No frame, no reading: points are solid only while a frame under 400 ms old exists.',
    states: [
      { label: 'idle, no frames (placeholder)', node: <Idle /> },
      { label: 'one fixture frame, SIMULATED (stale after 400 ms)', node: <Fixture /> },
      { label: 'voice process off', node: <Off /> },
    ],
  },
]
export default entries
